"""Runs the migrations against a throwaway database next to DATABASE_URL's. Skipped when Postgres isn't reachable."""
import uuid

import pytest
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

from tagger.config import ROOT, load_settings
from tagger.store import CONNECT_ARGS, metadata, migrate

VIEWS = {"llm_tag_comparison", "first_second_tag_comparison", "llm_tag_votes", "final_tag_summary",
         "human_tag_comparison", "final_results"}


@pytest.fixture
def scratch_url():
    url = load_settings().database_url
    if not url:
        pytest.skip("DATABASE_URL is not set")
    name = f"tagger_migration_test_{uuid.uuid4().hex[:8]}"
    admin = create_engine(make_url(url).set(database="postgres"), isolation_level="AUTOCOMMIT",
                          connect_args=CONNECT_ARGS)
    try:
        admin.connect().close()
    except Exception as e:
        pytest.skip(f"Postgres not reachable: {e}")
    yield make_url(url).set(database=name).render_as_string(hide_password=False)  # migrate() creates it
    with admin.connect() as conn:
        conn.exec_driver_sql(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
    admin.dispose()


def _config(url):
    from alembic.config import Config
    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    config.attributes["embedded"] = True
    return config


def test_upgrade_matches_metadata_and_is_repeatable(scratch_url):
    from alembic import command
    from alembic.util.exc import AutogenerateDiffsDetected

    migrate(scratch_url)  # creates the database and runs every revision
    migrate(scratch_url)  # nothing left to do: must not fail
    engine = create_engine(scratch_url)
    try:
        found = inspect(engine)
        assert set(metadata.tables) <= set(found.get_table_names())
        assert VIEWS <= set(found.get_view_names())
        with engine.connect() as conn:
            assert conn.execute(text("SELECT version_num FROM alembic_version")).scalar()
            assert conn.execute(text("SELECT count(*) FROM final_results")).scalar() == 0
        # the migrations and store.py's Table definitions must describe the same schema
        try:
            command.check(_config(scratch_url))
        except AutogenerateDiffsDetected as e:
            pytest.fail(f"store.py and the migrations differ: {e}")

        command.downgrade(_config(scratch_url), "base")
        left = inspect(engine)
        assert not (set(metadata.tables) & set(left.get_table_names()))
        assert not (VIEWS & set(left.get_view_names()))
    finally:
        engine.dispose()
